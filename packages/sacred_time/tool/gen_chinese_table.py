#!/usr/bin/env python3
"""Generates lib/src/chinese_table.dart from Hong Kong Observatory tables.

Download the yearly Gregorian-Lunar conversion tables first:

    https://www.hko.gov.hk/en/gts/time/calendar/text/files/T<year>e.txt

for every year 1901..2100 into one directory, then run:

    python3 -I tool/gen_chinese_table.py <directory> lib/src/chinese_table.dart
"""
import datetime
import re
import sys

FIRST_YEAR, LAST_YEAR = 1901, 2100
LINE = re.compile(r"^(\d{4})/(\d{1,2})/(\d{1,2})\s+(\S+)(\s+Lunar Month)?", re.IGNORECASE)


def read_days(directory):
    """Yields (date, lunar day, month number or None) for every table row."""
    for year in range(FIRST_YEAR, LAST_YEAR + 1):
        with open(f"{directory}/T{year}e.txt", encoding="ascii", errors="replace") as f:
            for line in f:
                m = LINE.match(line)
                if not m:
                    continue
                date = datetime.date(int(m[1]), int(m[2]), int(m[3]))
                if m[5]:
                    yield date, 1, int(re.match(r"\d+", m[4])[0])
                else:
                    yield date, int(m[4]), None


def fill_missing_rows(days):
    """Restores rows the source omits, when the lunar day count proves they
    fall inside a month (the 2069 table lacks 30 December)."""
    filled = [days[0]]
    for date, day, month in days[1:]:
        previous_date, previous_day, _ = filled[-1]
        gap = (date - previous_date).days
        if gap > 1 and month is None and day == previous_day + gap:
            for i in range(1, gap):
                missing = previous_date + datetime.timedelta(days=i)
                print(f"filled missing row {missing}")
                filled.append((missing, previous_day + i, None))
        filled.append((date, day, month))
    return filled


def main(directory, output):
    days = fill_missing_rows(list(read_days(directory)))

    # Every calendar day must be present exactly once, in order.
    for (a, _, _), (b, _, _) in zip(days, days[1:]):
        assert (b - a).days == 1, f"gap or repeat between {a} and {b}"
    assert days[0][0] == datetime.date(FIRST_YEAR, 1, 1)
    assert days[-1][0] == datetime.date(LAST_YEAR, 12, 31)

    # Lunar days must count up by one until the next month starts.
    for (_, d1, _), (date, d2, month) in zip(days, days[1:]):
        assert d2 == d1 + 1 or (month and d1 in (29, 30)), f"bad day at {date}"

    starts = [(date, month) for date, _, month in days if month]
    months = []  # (start date, month number, is leap, length)
    for i, (date, month) in enumerate(starts[:-1]):
        leap = i > 0 and starts[i - 1][1] == month
        length = (starts[i + 1][0] - date).days
        assert length in (29, 30), f"month at {date} has {length} days"
        months.append((date, month, leap, length))

    new_years = [i for i, m in enumerate(months) if m[1] == 1 and not m[2]]
    rows = []
    for a, b in zip(new_years, new_years[1:]):
        year_months = months[a:b]
        start = year_months[0][0]
        assert len(year_months) in (12, 13), f"year {start.year}"
        leaps = [m[1] for m in year_months if m[2]]
        assert len(leaps) == len(year_months) - 12, f"year {start.year}"
        offset = (start - datetime.date(start.year, 1, 1)).days
        bits = sum(1 << i for i, m in enumerate(year_months) if m[3] == 30)
        rows.append((start.year, offset << 17 | (leaps[0] if leaps else 0) << 13 | bits))

    assert [y for y, _ in rows] == list(range(rows[0][0], rows[-1][0] + 1))

    with open(output, "w", encoding="ascii") as f:
        f.write("// GENERATED by tool/gen_chinese_table.py from the Hong Kong\n")
        f.write("// Observatory Gregorian-Lunar conversion tables. Do not edit.\n\n")
        f.write(f"const chineseTableFirstYear = {rows[0][0]};\n\n")
        f.write("/// One entry per Chinese year, indexed from [chineseTableFirstYear].\n")
        f.write("///\n")
        f.write("/// bits 17+   : new year's day, as days after 1 January\n")
        f.write("/// bits 13-16 : the month the leap month follows, or 0\n")
        f.write("/// bits 0-12  : bit i set when the i-th month has 30 days\n")
        f.write("const chineseTable = <int>[\n")
        for i in range(0, len(rows), 8):
            chunk = ", ".join(f"0x{v:06x}" for _, v in rows[i : i + 8])
            f.write(f"  {chunk}, // {rows[i][0]}\n")
        f.write("];\n")
    print(f"wrote {len(rows)} years: {rows[0][0]}..{rows[-1][0]}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
