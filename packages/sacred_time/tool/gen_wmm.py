"""Writes lib/src/wmm2025.g.dart from NOAA's WMM2025.COF (the World
Magnetic Model 2025, public domain: "The WMM source code is in the public
domain and not licensed or under copyright", NCEI):

  python3 -I gen_wmm.py WMM2025.COF > ../lib/src/wmm2025.g.dart
"""
import hashlib
import sys

raw = open(sys.argv[1], 'rb').read()
lines = raw.decode().splitlines()
epoch = float(lines[0].split()[0])
rows = []
for line in lines[1:]:
    if line.startswith('9999'):
        break
    n, m, g, h, gd, hd = line.split()
    rows.append((int(n), int(m), g, h, gd, hd))
print('// Generated by tool/gen_wmm.py from NOAA NCEI\'s WMM2025.COF (the World')
print('// Magnetic Model 2025, public domain), SHA-256')
print(f'// {hashlib.sha256(raw).hexdigest()}. Do not edit.')
print()
print(f'const wmmEpoch = {epoch};')
print()
print('/// (n, m, g, h, dg/dt, dh/dt), nT and nT a year.')
print('const wmmCoefficients = <(int, int, double, double, double, double)>[')
for n, m, g, h, gd, hd in rows:
    print(f'  ({n}, {m}, {g}, {h}, {gd}, {hd}),')
print('];')
