"""Writes lib/src/indonesia_grid.g.dart: for every point on a 0.1° grid
over Indonesia and its neighbours, whether it is Indonesian: on
Indonesian land, or at sea nearer Indonesian land than any other
country's (up to 1.5°, about 165 km, out).

Places in the app are rounded to 0.1°, so each place is one of these
points. Land and sea are worked out on a grid five times finer (0.02°),
so the nearest coast decides a point in a strait, then read at 0.1°. The grid decides only which prayer-time reckoning a place gets
by default (Indonesia's ministry, or a choice), never a border.

  python3 -I gen_indonesia_grid.py ne_10m_admin_0_countries.geojson > \
      ../lib/src/indonesia_grid.g.dart

From Natural Earth's 1:10m Admin 0 countries (public domain).
"""
import base64
import hashlib
import json
import sys
from collections import deque

path = sys.argv[1]
raw = open(path, 'rb').read()
data = json.loads(raw)

SOUTH, NORTH, WEST, EAST = -12.0, 7.0, 94.0, 142.0
ROWS = round((NORTH - SOUTH) * 10) + 1
COLS = round((EAST - WEST) * 10) + 1
FINE = 5
STEP = 10 * FINE
FROWS = (ROWS - 1) * FINE + 1
FCOLS = (COLS - 1) * FINE + 1
REACH = 15 * FINE

owner = [[None] * FCOLS for _ in range(FROWS)]


def fill(rings, code):
    lats = [p[1] for r in rings for p in r]
    lons = [p[0] for r in rings for p in r]
    if max(lats) < SOUTH or min(lats) > NORTH:
        return
    if max(lons) < WEST or min(lons) > EAST:
        return
    i0 = max(0, int((min(lats) - SOUTH) * STEP) - 1)
    i1 = min(FROWS - 1, int((max(lats) - SOUTH) * STEP) + 1)
    for i in range(i0, i1 + 1):
        y = SOUTH + i / STEP
        xs = []
        for ring in rings:
            for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
                if (y1 > y) != (y2 > y):
                    xs.append(x1 + (y - y1) * (x2 - x1) / (y2 - y1))
        xs.sort()
        for a, b in zip(xs[0::2], xs[1::2]):
            j0 = max(0, -int(-(a - WEST) * STEP // 1))
            j1 = min(FCOLS - 1, int((b - WEST) * STEP // 1))
            for j in range(j0, j1 + 1):
                x = WEST + j / STEP
                if a <= x <= b:
                    owner[i][j] = code


for feature in data['features']:
    code = feature['properties']['ADM0_A3']
    geometry = feature['geometry']
    polygons = (geometry['coordinates'] if geometry['type'] == 'MultiPolygon'
                else [geometry['coordinates']])
    for polygon in polygons:
        fill([[tuple(p[:2]) for p in ring] for ring in polygon], code)

# The sea: each point to the nearest land, spreading out a step at a time.
queue = deque()
distance = [[None] * FCOLS for _ in range(FROWS)]
for i in range(FROWS):
    for j in range(FCOLS):
        if owner[i][j] is not None:
            distance[i][j] = 0
            queue.append((i, j))
while queue:
    i, j = queue.popleft()
    if distance[i][j] >= REACH:
        continue
    for di, dj in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        a, b = i + di, j + dj
        if 0 <= a < FROWS and 0 <= b < FCOLS and distance[a][b] is None:
            distance[a][b] = distance[i][j] + 1
            owner[a][b] = owner[i][j]
            queue.append((a, b))

bits = bytearray((ROWS * COLS + 7) // 8)
count = 0
for i in range(ROWS):
    for j in range(COLS):
        if owner[i * FINE][j * FINE] == 'IDN':
            k = i * COLS + j
            bits[k >> 3] |= 1 << (k & 7)
            count += 1

encoded = base64.b64encode(bytes(bits)).decode()
lines = [encoded[k:k + 76] for k in range(0, len(encoded), 76)]
print(f"""// Generated by tool/gen_indonesia_grid.py from Natural Earth 1:10m
// Admin 0 countries (public domain), SHA-256
// {hashlib.sha256(raw).hexdigest()}.
// {count} of {ROWS * COLS} points Indonesian. Do not edit.

const indonesiaSouth = {SOUTH};
const indonesiaWest = {WEST};
const indonesiaRows = {ROWS};
const indonesiaColumns = {COLS};

const indonesiaGrid =
""" + '\n'.join(f"    '{line}'" for line in lines) + ';')
