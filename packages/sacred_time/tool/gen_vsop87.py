"""Writes lib/src/vsop87d.g.dart: the planets' series of VSOP87D
(Bretagnon and Francou, Astron. Astrophys. 202, 309, 1988), heliocentric
spherical variables, ecliptic and equinox of date, from IMCCE's files:

  python3 -I tool/gen_vsop87.py /path/to/vsop87/ > lib/src/vsop87d.g.dart

where the folder holds VSOP87D.mer, .ven, .ear, .mar, .jup, .sat, .ura
and .nep from https://ftp.imcce.fr/pub/ephem/planets/vsop87/.

Terms are kept whose amplitude A, or A times 0.2 to the power of t
(within two centuries of J2000), reaches 1e-7 (radians, or AU for the
distance): against the full series this leaves at most 0.3 seconds of
arc in longitude and latitude, and 2e-6 AU in distance, from 1900 to
2100 (checked when the file was made, and by the engine's tests against
IMCCE's own vsop87.chk).
"""
import hashlib
import os
import re
import sys

EPS = 1e-7
folder = sys.argv[1]
names = [('mer', 'mercury'), ('ven', 'venus'), ('ear', 'earth'),
         ('mar', 'mars'), ('jup', 'jupiter'), ('sat', 'saturn'),
         ('ura', 'uranus'), ('nep', 'neptune')]

print('// GENERATED by tool/gen_vsop87.py; do not edit.')
print('// VSOP87D (Bretagnon and Francou 1988), from IMCCE, truncated at')
print(f'// {EPS:g}. Sources:')
for short, _ in names:
    path = os.path.join(folder, f'VSOP87D.{short}')
    digest = hashlib.sha256(open(path, 'rb').read()).hexdigest()
    print(f'//   VSOP87D.{short} sha256 {digest}')
print()
print('/// For each body, its longitude, latitude and distance, each a list')
print('/// by power of the time of series of amplitude, phase and frequency,')
print('/// flattened.')
print('const vsop87d = <String, List<List<List<double>>>>{')
total = 0
for short, name in names:
    series = {}
    current = None
    # Every block says how many terms it has: a file cut short in the
    # download fails here rather than giving a wrong planet.
    expected, seen = {}, {}
    for line in open(os.path.join(folder, f'VSOP87D.{short}')):
        if 'VARIABLE' in line:
            m = re.search(r'VARIABLE\s+(\d).*\*T\*\*(\d)\s+(\d+) TERMS?', line)
            current = (int(m.group(1)), int(m.group(2)))
            series[current] = []
            expected[current] = int(m.group(3))
            seen[current] = 0
            continue
        f = line.split()
        if current and len(f) >= 3:
            seen[current] += 1
            a, b, c = float(f[-3]), float(f[-2]), float(f[-1])
            k = current[1]
            if a >= EPS or (k and a * 0.2 ** k >= EPS):
                series[current].append((a, b, c))
    assert seen == expected, (short, seen, expected)
    assert sorted({v for v, _ in expected}) == [1, 2, 3], short
    print(f"  '{name}': [")
    for var in (1, 2, 3):
        print('    [')
        powers = sorted(k for v, k in series if v == var)
        for k in range(max(powers) + 1):
            terms = series.get((var, k), [])
            total += len(terms)
            flat = ', '.join(f'{a!r}, {b!r}, {c!r}' for a, b, c in terms)
            print(f'      [{flat}],')
        print('    ],')
    print('  ],')
print('};')
print(f'{total} terms', file=sys.stderr)
